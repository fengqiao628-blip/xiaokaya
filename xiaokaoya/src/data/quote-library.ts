export const quoteLibrary: LibraryEntry[] = [
  ...legacy.map((quote) => ({ ...quote, attribution: { ...originalAttribution } })),
  ...Object.entries(originals).flatMap(([category, texts], group) =>
    texts.map((text, index) => ({
      id: `quote-v6-original-${String(group * 20 + index + 1).padStart(3, '0')}`,
      text,
      category,
      attribution: { ...originalAttribution },
    })),
  ),
  ...classics.map(([text, author, work, sourceTitle, sourceUrl, kind], i) => ({
    id: `quote-v6-classic-${String(i + 1).padStart(3, '0')}`,
    text,
    category: kind === 'poetry' ? '古典诗词' : '名言·劝学',
    attribution: {
      kind,
      origin: 'builtin' as const,
      author,
      work,
      sourceTitle: sourceUrl.includes('upload.wikimedia.org')
        ? '《杜少陵集详注》古籍影印，卷一原文核对（简体转换）'
        : sourceTitle,
      sourceUrl,
    },
  })),
]
