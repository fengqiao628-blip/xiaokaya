import { db } from '../../data/database'
export async function readDashboard() {
  return db.transaction('r', db.tables, async () => {
    const [
      subjects,
      plans,
      cycles,
      tasks,
      preferences,
      sessions,
      segments,
      dailyQuotes,
      cycleStatuses,
      materials,
      chapters,
      materialProgress,
      subjectParts,
      weeklyPlans,
      weeklySubjectTargets,
      taskScheduleHistory,
      examMilestones,
      focusTimers,
      quotes,
      quoteDetails,
      quoteFavorites,
      quoteHistory,
      experienceSettings,
    ] = await Promise.all([
      db.subjects.orderBy('order').toArray(),
      db.annualPlans.toArray(),
      db.cycles.toArray(),
      db.tasks.toArray(),
      db.preferences.get('preferences'),
      db.studySessions.toArray(),
      db.timeSegments.toArray(),
      db.dailyQuotes.toArray(),
      db.cycleStatuses.toArray(),
      db.materials.toArray(),
      db.chapters.toArray(),
      db.materialProgress.toArray(),
      db.subjectParts.toArray(),
      db.weeklyPlans.toArray(),
      db.weeklySubjectTargets.toArray(),
      db.taskScheduleHistory.toArray(),
      db.examMilestones.toArray(),
      db.focusTimers.toArray(),
      db.quotes.toArray(),
      db.quoteDetails.toArray(),
      db.quoteFavorites.toArray(),
      db.quoteHistory.toArray(),
      db.experienceSettings.get('experience'),
    ])
    return {
      subjects,
      plans,
      cycles,
      tasks,
      preferences,
      sessions,
      segments,
      dailyQuotes,
      cycleStatuses,
      materials,
      chapters,
      materialProgress,
      subjectParts,
      weeklyPlans,
      weeklySubjectTargets,
      taskScheduleHistory,
      examMilestones,
      focusTimers,
      quotes,
      quoteDetails,
      quoteFavorites,
      quoteHistory,
      experienceSettings,
    }
  })
}
export type Snapshot = Awaited<ReturnType<typeof readDashboard>>
export type Runner = (
  operation: () => Promise<unknown>,
  message: string | (() => string),
) => Promise<boolean>
