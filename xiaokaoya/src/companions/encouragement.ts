export type EncouragementMood = keyof typeof encouragementLibrary
export function pickEncouragement(mood: EncouragementMood, seed: string, rotation = 0): string {
  let hash = 0
  for (const char of seed) hash = (hash * 31 + char.charCodeAt(0)) >>> 0
  const list = encouragementLibrary[mood]
  return list[(hash + Math.max(0, Math.floor(rotation))) % list.length]
}

export function learningMood(
  tasks: Task[],
  timers: FocusTimer[],
  today: string,
): EncouragementMood {
  const active = timers.find((timer) => ['running', 'paused', 'review'].includes(timer.status))
  if (active?.status === 'running') return 'studying'
  if (active?.reason === 'due') return 'due'
  if (active?.status === 'paused') return 'paused'
  if (active?.status === 'review') return 'ended'
  const current = tasks.filter((task) => task.plannedDate === today && task.status !== 'cancelled')
  if (current.length && current.every((task) => task.status === 'completed')) return 'allDone'
  if (
    timers.some(
      (timer) => timer.status === 'saved' && todayKey(new Date(timer.updatedAt)) === today,
    )
  )
    return 'ended'
  if (current.some((task) => task.status === 'in_progress')) return 'studying'
  if (current.some((task) => task.status === 'completed')) return 'completed'
  return 'ready'
}
